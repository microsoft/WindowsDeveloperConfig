        @{ Name = 'EdgeNewTab'; KeyPath = 'HKLM\SOFTWARE\Policies\Microsoft\Edge'; ValueName = 'NewTabPageLocation';  Value = 'about:blank'; Type = 'String'; Description = 'Set Edge new tab to blank' }
